export function rfqCopy(language: string) {
  const code = language.split("-")[0];
  const copy =
    code === "ka" ? ka : code === "ru" ? ru : code === "ar" ? ar : en;
  return {
    text: (key: Key) => copy[key],
    code,
    dir: code === "ar" ? ("rtl" as const) : ("ltr" as const),
  };
}
